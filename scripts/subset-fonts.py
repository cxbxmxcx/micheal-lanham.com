"""Build the self-hosted web fonts in public/fonts/.

The site used to load Inter, Space Grotesk and JetBrains Mono from Google
Fonts, a render-blocking third-party stylesheet that also sent every
visitor's IP address to Google. This script rebuilds the local copies:

1. Download the variable sources from google/fonts at a pinned commit and
   check their SHA-256.
2. Keep Google's "latin" character set plus the arrows the site uses
   (U+2190-2199), and drop hinting and OpenType features the pages never
   turn on.
3. Limit each family to the weights the pages use: Inter 400-700 and
   JetBrains Mono 400-700 stay variable; Space Grotesk becomes static 600
   (the site) and 700 (demo headings).
4. Write the woff2 files, public/fonts/fonts.css for the standalone demo
   pages, and the OFL licence for each family.

src/index.css declares the same faces for the main site; keep them in step.
Re-run only to change the character set or the weights:

    python -m pip install fonttools brotli
    python scripts/subset-fonts.py
"""
import hashlib
import io
import urllib.request
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

COMMIT = '6c1dbe27dcf7d817d4b62cec033ba77fa8e2a5ec'
RAW = f'https://raw.githubusercontent.com/google/fonts/{COMMIT}/ofl'
OUT = Path(__file__).resolve().parent.parent / 'public' / 'fonts'

SOURCES = {
    'Inter': ('inter/Inter%5Bopsz%2Cwght%5D.ttf', '29160a80ff49ddcab2c97711247e08b1fab27a484a329ce8b813d820dc559031', 'inter'),
    'Space Grotesk': ('spacegrotesk/SpaceGrotesk%5Bwght%5D.ttf', 'acad6de1fc93436f5c0f1f4137751ef04f1aea3063e7036535970ffcfbd79f72', 'spacegrotesk'),
    'JetBrains Mono': ('jetbrainsmono/JetBrainsMono%5Bwght%5D.ttf', '48715a42ec242c21e9f02692891e147d022299a52e48d5e413e1a942193ffeda', 'jetbrainsmono'),
}
# (family, file name, axis limits, CSS font-weight)
FACES = [
    ('Inter', 'inter-latin-wght.woff2', {'opsz': 14, 'wght': (400, 700)}, '400 700'),
    ('Space Grotesk', 'space-grotesk-latin-600.woff2', {'wght': 600}, '600'),
    ('Space Grotesk', 'space-grotesk-latin-700.woff2', {'wght': 700}, '700'),
    ('JetBrains Mono', 'jetbrains-mono-latin-wght.woff2', {'wght': (400, 700)}, '400 700'),
]
# Google Fonts' "latin" subset, plus the arrows used for link glyphs.
UNICODES = (
    list(range(0x20, 0x7F)) + list(range(0xA0, 0x100))
    + [0x131, 0x152, 0x153, 0x2BB, 0x2BC, 0x2C6, 0x2DA, 0x2DC, 0x304, 0x308, 0x329]
    + list(range(0x2000, 0x2070)) + [0x20AC, 0x2122, 0x2212, 0x2215, 0xFEFF, 0xFFFD]
    + list(range(0x2190, 0x219A))
)
FEATURES = ['kern', 'liga', 'calt', 'ccmp', 'locl', 'mark', 'mkmk', 'case']
UNICODE_RANGE = 'U+0020-007E, U+00A0-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2190-2199, U+2212, U+2215, U+FEFF, U+FFFD'


def fetch(path, sha256=None):
    data = urllib.request.urlopen(f'{RAW}/{path}').read()
    if sha256 and hashlib.sha256(data).hexdigest() != sha256:
        raise SystemExit(f'{path}: unexpected SHA-256; update the pinned commit and hash deliberately')
    return data


def build(source, axes):
    font = TTFont(io.BytesIO(source), lazy=False)
    options = subset.Options()
    options.layout_features = FEATURES
    options.hinting = False
    options.name_IDs = ['*']
    options.notdef_outline = True
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=UNICODES)
    subsetter.subset(font)  # subset before instancing; the reverse trips over gvar
    font = instancer.instantiateVariableFont(font, axes)
    font.flavor = 'woff2'
    out = io.BytesIO()
    font.save(out)
    return out.getvalue()


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    sources = {family: fetch(path, sha) for family, (path, sha, _) in SOURCES.items()}
    css = ['/* Self-hosted fonts for the standalone demo pages. Generated by',
           '   scripts/subset-fonts.py; src/index.css declares the same faces. */']
    for family, file, axes, weight in FACES:
        data = build(sources[family], axes)
        (OUT / file).write_bytes(data)
        print(f'{file}: {len(data):,} bytes')
        css.append(f"@font-face {{ font-family: '{family}'; font-style: normal; font-weight: {weight}; font-display: swap; "
                   f"src: url('/fonts/{file}') format('woff2'); unicode-range: {UNICODE_RANGE}; }}")
    (OUT / 'fonts.css').write_text('\n'.join(css) + '\n', encoding='utf-8')
    for family, (_, _, folder) in SOURCES.items():
        (OUT / f"OFL-{family.replace(' ', '')}.txt").write_bytes(fetch(f'{folder}/OFL.txt'))


if __name__ == '__main__':
    main()
